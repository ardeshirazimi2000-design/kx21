import crypto from 'node:crypto';
import { mkdir, rename, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { loadAuthUser } from '../auth/middleware.js';
import { pool, query, type Db } from '../db/pool.js';
import { decryptText, encryptText } from '../lib/crypto.js';

/**
 * Generates the two Asterisk files Rasa owns, from its own data. The static configuration of the PBX container
 * (deploy/pbx/conf) includes them; nothing else in Asterisk is edited by Rasa.
 *   pjsip_extensions.conf  one endpoint + auth + aor per live extension
 *   extensions_rasa.conf   the dial plan of those extensions, and where city-line calls ring
 * Files are written to a temporary name and renamed, so Asterisk never reads half a file.
 */

export interface PbxExtension {
  number: string;
  name: string;
  secret: string;
  external: boolean;
}

export interface InboundSettings {
  targets: string[];
  ringSeconds: number;
}

export const DEFAULT_INBOUND: InboundSettings = { targets: [], ringSeconds: 40 };

export const SOUND_KINDS = ['greeting', 'closed'] as const;
export type SoundKind = (typeof SOUND_KINDS)[number];
/** Where Asterisk finds the prompts (the pbx-config volume is mounted there); no extension: Asterisk picks .wav. */
export const SOUND_PATH = '/etc/asterisk/rasa/sounds';

export const IVR_DAYS = ['sat', 'sun', 'mon', 'tue', 'wed', 'thu', 'fri'] as const;
export type IvrDay = (typeof IVR_DAYS)[number];

export interface IvrOption {
  digit: string;
  label: string;
  targets: string[];
}

/** The auto-attendant (تلفن گویا) of the city line. When off, city-line calls ring the inbound targets directly. */
export interface IvrSettings {
  enabled: boolean;
  options: IvrOption[];
  /** The caller may also dial an extension number directly during the greeting. */
  directDial: boolean;
  /** Seconds to wait for a key after the greeting; then the call goes to the inbound targets (operator). */
  waitSeconds: number;
  ringSeconds: number;
  workHours: { days: IvrDay[]; start: string; end: string };
  /** Outside work hours, play the "closed" message and hang up. */
  afterHoursEnabled: boolean;
}

export const DEFAULT_IVR: IvrSettings = {
  enabled: false,
  options: [],
  directDial: true,
  waitSeconds: 5,
  ringSeconds: 40,
  workHours: { days: ['sat', 'sun', 'mon', 'tue', 'wed'], start: '08:00', end: '16:00' },
  afterHoursEnabled: false,
};

/**
 * Checks a prompt is what Asterisk plays natively: RIFF/WAVE, PCM, mono, 8000 Hz, 16-bit. The browser converts
 * recordings and uploads to this before sending. Returns null when valid, otherwise the reason (Persian).
 */
export function wavProblem(buf: Buffer): string | null {
  if (buf.length < 44 || buf.toString('ascii', 0, 4) !== 'RIFF' || buf.toString('ascii', 8, 12) !== 'WAVE') return 'فایل WAV معتبر نیست';
  let off = 12;
  let fmt: { format: number; channels: number; rate: number; bits: number } | null = null;
  let dataLen = -1;
  while (off + 8 <= buf.length) {
    const id = buf.toString('ascii', off, off + 4);
    const size = buf.readUInt32LE(off + 4);
    const body = off + 8;
    if (id === 'fmt ' && size >= 16 && body + 16 <= buf.length) {
      fmt = { format: buf.readUInt16LE(body), channels: buf.readUInt16LE(body + 2), rate: buf.readUInt32LE(body + 4), bits: buf.readUInt16LE(body + 14) };
    } else if (id === 'data') {
      dataLen = Math.min(size, buf.length - body);
      break;
    }
    off = body + size + (size % 2);
  }
  if (!fmt || dataLen < 0) return 'فایل WAV معتبر نیست';
  if (fmt.format !== 1 || fmt.channels !== 1 || fmt.rate !== 8000 || fmt.bits !== 16) return 'صدا باید PCM تک‌کاناله ۸۰۰۰ هرتز ۱۶ بیتی باشد';
  if (dataLen < 8000) return 'صدا کوتاه‌تر از نیم ثانیه است';
  if (dataLen > 16000 * 180) return 'صدا بیش از سه دقیقه است';
  return null;
}

/** A SIP password: 24 characters from an unambiguous alphabet (never the extension number). */
export function newSipSecret() {
  const alphabet = 'ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz23456789';
  const bytes = crypto.randomBytes(24);
  return [...bytes].map((b) => alphabet[b % alphabet.length]).join('');
}

/** Text that goes into a config value: no line breaks, quotes, semicolons (comments) or brackets. */
const clean = (s: string) => s.replace(/[\r\n"';[\]\\<>]/g, ' ').replace(/\s+/g, ' ').trim().slice(0, 60);

export function renderPjsip(exts: PbxExtension[]): string {
  const out = ['; Generated by Rasa (communications module). Do not edit: changes are overwritten.', ''];
  for (const e of exts) {
    if (!/^[0-9]{2,6}$/.test(e.number) || !/^[A-Za-z0-9]{16,64}$/.test(e.secret)) continue;
    out.push(
      `[${e.number}](rasa-endpoint)`,
      'type=endpoint',
      `context=${e.external ? 'rasa-external' : 'rasa-internal'}`,
      `auth=${e.number}-auth`,
      `aors=${e.number}`,
      `callerid="${clean(e.name)}" <${e.number}>`,
      '',
      `[${e.number}-auth]`,
      'type=auth',
      'auth_type=userpass',
      `username=${e.number}`,
      `password=${e.secret}`,
      '',
      `[${e.number}](rasa-aor)`,
      'type=aor',
      '',
    );
  }
  return out.join('\n');
}

function dialTargets(targets: string[], ring: number) {
  return `Dial(${targets.map((t) => `PJSIP/${t}`).join('&')},${ring})`;
}

const hhmm = (t: string) => (/^([01][0-9]|2[0-3]):[0-5][0-9]$/.test(t) ? t : null);

/**
 * [rasa-extensions] is what phones dial; [rasa-inbound] is where city-line calls land (rasa-from-trunk). With the
 * auto-attendant on (and its greeting recorded), the caller hears the greeting and presses a digit or an extension.
 * Callers from the city line only ever reach Dial(PJSIP/<extension>): no outbound context is included here.
 */
export function renderDialplan(exts: PbxExtension[], inbound: InboundSettings, ivr: IvrSettings = DEFAULT_IVR, sounds: SoundKind[] = []): string {
  const live = new Set(exts.filter((e) => /^[0-9]{2,6}$/.test(e.number)).map((e) => e.number));
  const ivrOn = ivr.enabled && sounds.includes('greeting');
  const out = ['; Generated by Rasa (communications module). Do not edit: changes are overwritten.', '', '[rasa-extensions]'];
  for (const n of live) out.push(`exten => ${n},1,Dial(PJSIP/${n},30)`, ' same => n,Hangup()');
  // Internal test number of the auto-attendant: an extension can hear it without a city line.
  if (ivrOn) out.push('exten => *99,1,Goto(rasa-inbound,s,1)');

  out.push('', '[rasa-inbound]');
  const targets = inbound.targets.filter((t) => live.has(t));
  const ring = Math.min(120, Math.max(10, Math.round(inbound.ringSeconds) || 40));
  // Where a call goes without a choice: the inbound targets (operator), or a polite message.
  const fallback = targets.length ? [dialTargets(targets, ring), 'Hangup()'] : ['Answer()', 'Playback(ss-noservice)', 'Hangup()'];
  const steps = (name: string, apps: string[]) => apps.forEach((a, i) => out.push(i ? ` same => n,${a}` : `exten => ${name},1,${a}`));

  if (!ivrOn) {
    steps('s', fallback);
    out.push('');
    return out.join('\n');
  }

  // Each step of the "s" extension, with an optional priority label.
  const head: [string, string?][] = [];
  const days = IVR_DAYS.filter((d) => ivr.workHours.days.includes(d));
  const start = hhmm(ivr.workHours.start);
  const end = hhmm(ivr.workHours.end);
  if (ivr.afterHoursEnabled && start && end && start < end) {
    head.push(
      [days.length ? `GotoIfTime(${start}-${end},${days.join('&')},*,*,Asia/Tehran?open)` : 'NoOp(no work days)'],
      ['Answer()'],
      ['Wait(1)'],
      [sounds.includes('closed') ? `Playback(${SOUND_PATH}/closed)` : 'Playback(ss-noservice)'],
      ['Hangup()'],
    );
  }
  const wait = Math.min(30, Math.max(2, Math.round(ivr.waitSeconds) || 5));
  head.push(
    ['Answer()', 'open'],
    ['Set(RASA_TRIES=0)'],
    ['Wait(1)'],
    ['Set(TIMEOUT(digit)=3)'],
    [`Background(${SOUND_PATH}/greeting)`, 'menu'],
    [`WaitExten(${wait})`],
    ['Goto(t,1)'],
  );
  head.forEach(([app, label], i) => out.push(i ? ` same => n${label ? `(${label})` : ''},${app}` : `exten => s,1${label ? `(${label})` : ''},${app}`));

  const optRing = Math.min(120, Math.max(10, Math.round(ivr.ringSeconds) || 40));
  const digits = new Set<string>();
  for (const o of ivr.options) {
    if (!/^[0-9]$/.test(o.digit) || digits.has(o.digit)) continue;
    const t = [...new Set(o.targets)].filter((x) => live.has(x));
    if (!t.length) continue;
    digits.add(o.digit);
    out.push(`; ${clean(o.label) || o.digit}`);
    steps(o.digit, [dialTargets(t, optRing), 'Hangup()']);
  }
  if (ivr.directDial) for (const n of live) if (!digits.has(n)) steps(n, [dialTargets([n], optRing), 'Hangup()']);
  steps('t', fallback);
  steps('i', ['Playback(invalid)', 'Set(RASA_TRIES=$[${RASA_TRIES} + 1])', 'GotoIf($[${RASA_TRIES} < 3]?s,menu)', 'Goto(t,1)']);
  out.push('');
  return out.join('\n');
}

async function writeAtomic(file: string, text: string | Buffer) {
  const tmp = `${file}.${process.pid}.tmp`;
  await writeFile(tmp, text, { mode: 0o640 });
  await rename(tmp, file);
}

/**
 * Live extensions (active or being provisioned, owner still active) with their SIP secret; a missing secret is
 * generated and stored encrypted.
 */
export async function liveExtensions(db: Db = pool): Promise<PbxExtension[]> {
  const rows = await query(
    `SELECT e.id, e.extension_number, e.sip_secret_enc, e.user_id, u.full_name FROM communication_extensions e JOIN users u ON u.id = e.user_id
      WHERE e.status IN ('active', 'provisioning') AND u.is_active ORDER BY e.extension_number`,
    [],
    db,
  );
  const out: PbxExtension[] = [];
  const canExternal = new Map<string, boolean>();
  for (const r of rows) {
    let secret: string;
    if (r.sip_secret_enc) secret = decryptText(r.sip_secret_enc);
    else {
      secret = newSipSecret();
      await query('UPDATE communication_extensions SET sip_secret_enc = $2 WHERE id = $1 AND sip_secret_enc IS NULL', [r.id, encryptText(secret)], db);
    }
    if (!canExternal.has(r.user_id)) canExternal.set(r.user_id, !!(await loadAuthUser(r.user_id, db))?.can('communications.call.external'));
    out.push({ number: r.extension_number, name: r.full_name, secret, external: canExternal.get(r.user_id)! });
  }
  return out;
}

export async function inboundSettings(db: Db = pool): Promise<InboundSettings> {
  const [r] = await query(`SELECT value FROM communication_settings WHERE key = 'inbound'`, [], db);
  return { ...DEFAULT_INBOUND, ...(r?.value ?? {}) };
}

export async function ivrSettings(db: Db = pool): Promise<IvrSettings> {
  const [r] = await query(`SELECT value FROM communication_settings WHERE key = 'ivr'`, [], db);
  const v = r?.value ?? {};
  return { ...DEFAULT_IVR, ...v, workHours: { ...DEFAULT_IVR.workHours, ...(v.workHours ?? {}) } };
}

/** Writes both files (and the auto-attendant prompts) into dir; returns the live extension numbers. */
export async function writePbxConfig(dir: string, db: Db = pool): Promise<string[]> {
  const exts = await liveExtensions(db);
  const sounds = await query(`SELECT key, data FROM communication_sounds ORDER BY key`, [], db);
  await mkdir(path.join(dir, 'sounds'), { recursive: true, mode: 0o750 });
  for (const k of SOUND_KINDS) {
    const row = sounds.find((r) => r.key === k);
    if (row) await writeAtomic(path.join(dir, 'sounds', `${k}.wav`), row.data);
    else await rm(path.join(dir, 'sounds', `${k}.wav`), { force: true });
  }
  await writeAtomic(path.join(dir, 'pjsip_extensions.conf'), renderPjsip(exts));
  const dialplan = renderDialplan(exts, await inboundSettings(db), await ivrSettings(db), sounds.map((r) => r.key as SoundKind));
  await writeAtomic(path.join(dir, 'extensions_rasa.conf'), dialplan);
  return exts.map((e) => e.number);
}
