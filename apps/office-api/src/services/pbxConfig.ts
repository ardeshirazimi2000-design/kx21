import crypto from 'node:crypto';
import { mkdir, rename, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { loadAuthUser } from '../auth/middleware.js';
import { pool, query, type Db } from '../db/pool.js';
import { decryptText, encryptText } from '../lib/crypto.js';

/**
 * Generates the two Asterisk files Rasa owns, from its own data. The static configuration of the PBX container
 * (deploy/pbx/conf) includes them; nothing else in Asterisk is edited by Rasa.
 *   pjsip_extensions.conf  one endpoint + auth + aor per live extension
 *   extensions_rasa.conf   the dial plan of those extensions, and where city-line calls ring
 * Files are written to a temporary name and renamed, so Asterisk never reads half a file.
 */

export interface PbxExtension {
  number: string;
  name: string;
  secret: string;
  external: boolean;
}

export interface InboundSettings {
  targets: string[];
  ringSeconds: number;
}

export const DEFAULT_INBOUND: InboundSettings = { targets: [], ringSeconds: 40 };

/** A SIP password: 24 characters from an unambiguous alphabet (never the extension number). */
export function newSipSecret() {
  const alphabet = 'ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz23456789';
  const bytes = crypto.randomBytes(24);
  return [...bytes].map((b) => alphabet[b % alphabet.length]).join('');
}

/** Text that goes into a config value: no line breaks, quotes, semicolons (comments) or brackets. */
const clean = (s: string) => s.replace(/[\r\n"';[\]\\<>]/g, ' ').replace(/\s+/g, ' ').trim().slice(0, 60);

export function renderPjsip(exts: PbxExtension[]): string {
  const out = ['; Generated by Rasa (communications module). Do not edit: changes are overwritten.', ''];
  for (const e of exts) {
    if (!/^[0-9]{2,6}$/.test(e.number) || !/^[A-Za-z0-9]{16,64}$/.test(e.secret)) continue;
    out.push(
      `[${e.number}](rasa-endpoint)`,
      'type=endpoint',
      `context=${e.external ? 'rasa-external' : 'rasa-internal'}`,
      `auth=${e.number}-auth`,
      `aors=${e.number}`,
      `callerid="${clean(e.name)}" <${e.number}>`,
      '',
      `[${e.number}-auth]`,
      'type=auth',
      'auth_type=userpass',
      `username=${e.number}`,
      `password=${e.secret}`,
      '',
      `[${e.number}](rasa-aor)`,
      'type=aor',
      '',
    );
  }
  return out.join('\n');
}

export function renderDialplan(exts: PbxExtension[], inbound: InboundSettings): string {
  const live = new Set(exts.map((e) => e.number));
  const out = ['; Generated by Rasa (communications module). Do not edit: changes are overwritten.', '', '[rasa-extensions]'];
  for (const e of exts) {
    if (!/^[0-9]{2,6}$/.test(e.number)) continue;
    out.push(`exten => ${e.number},1,Dial(PJSIP/${e.number},30)`, ' same => n,Hangup()');
  }
  out.push('', '[rasa-inbound]');
  const targets = inbound.targets.filter((t) => live.has(t));
  const ring = Math.min(120, Math.max(10, Math.round(inbound.ringSeconds) || 40));
  if (targets.length) {
    out.push(`exten => s,1,Dial(${targets.map((t) => `PJSIP/${t}`).join('&')},${ring})`, ' same => n,Hangup()');
  } else {
    // No destination chosen yet in Rasa: answer politely instead of ringing nowhere.
    out.push('exten => s,1,Answer()', ' same => n,Playback(ss-noservice)', ' same => n,Hangup()');
  }
  out.push('');
  return out.join('\n');
}

async function writeAtomic(file: string, text: string) {
  const tmp = `${file}.${process.pid}.tmp`;
  await writeFile(tmp, text, { mode: 0o640 });
  await rename(tmp, file);
}

/**
 * Live extensions (active or being provisioned, owner still active) with their SIP secret; a missing secret is
 * generated and stored encrypted.
 */
export async function liveExtensions(db: Db = pool): Promise<PbxExtension[]> {
  const rows = await query(
    `SELECT e.id, e.extension_number, e.sip_secret_enc, e.user_id, u.full_name FROM communication_extensions e JOIN users u ON u.id = e.user_id
      WHERE e.status IN ('active', 'provisioning') AND u.is_active ORDER BY e.extension_number`,
    [],
    db,
  );
  const out: PbxExtension[] = [];
  const canExternal = new Map<string, boolean>();
  for (const r of rows) {
    let secret: string;
    if (r.sip_secret_enc) secret = decryptText(r.sip_secret_enc);
    else {
      secret = newSipSecret();
      await query('UPDATE communication_extensions SET sip_secret_enc = $2 WHERE id = $1 AND sip_secret_enc IS NULL', [r.id, encryptText(secret)], db);
    }
    if (!canExternal.has(r.user_id)) canExternal.set(r.user_id, !!(await loadAuthUser(r.user_id, db))?.can('communications.call.external'));
    out.push({ number: r.extension_number, name: r.full_name, secret, external: canExternal.get(r.user_id)! });
  }
  return out;
}

export async function inboundSettings(db: Db = pool): Promise<InboundSettings> {
  const [r] = await query(`SELECT value FROM communication_settings WHERE key = 'inbound'`, [], db);
  return { ...DEFAULT_INBOUND, ...(r?.value ?? {}) };
}

/** Writes both files into dir; returns the live extension numbers. */
export async function writePbxConfig(dir: string, db: Db = pool): Promise<string[]> {
  const exts = await liveExtensions(db);
  await mkdir(dir, { recursive: true });
  await writeAtomic(path.join(dir, 'pjsip_extensions.conf'), renderPjsip(exts));
  await writeAtomic(path.join(dir, 'extensions_rasa.conf'), renderDialplan(exts, await inboundSettings(db)));
  return exts.map((e) => e.number);
}
