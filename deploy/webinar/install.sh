#!/usr/bin/env bash
# Installs the built-in webinar (Jitsi Meet) next to the commissions platform and connects the two.
#
#   cd ~/kx21 && sudo bash deploy/webinar/install.sh webinar.example.ir admin@example.ir
#
# Requirements: the domain's DNS A record points to this server, ports 80/tcp, 443/tcp and
# 10000/udp are free and open, Docker with the compose plugin is installed.
set -euo pipefail

DOMAIN="${1:-}"
EMAIL="${2:-}"
if [[ -z "$DOMAIN" || -z "$EMAIL" ]]; then
  echo "استفاده: sudo bash deploy/webinar/install.sh <دامنه وبینار> <ایمیل برای گواهی SSL>"
  echo "مثال:   sudo bash deploy/webinar/install.sh webinar.maliyarapp.ir info@maliyarapp.ir"
  exit 1
fi

DIR="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$DIR/../.." && pwd)"
cd "$DIR"

say() { printf '\n\033[1;36m» %s\033[0m\n' "$*"; }
fail() { printf '\n\033[1;31m✗ %s\033[0m\n' "$*"; exit 1; }

command -v docker >/dev/null || fail "Docker نصب نیست."
docker compose version >/dev/null 2>&1 || fail "افزونه docker compose نصب نیست."

# ── Public IP and DNS ────────────────────────────────────────────────────────
PUBLIC_IP="${PUBLIC_IP:-}"
if [[ -z "$PUBLIC_IP" ]]; then
  PUBLIC_IP="$(curl -fsS --max-time 5 https://api.ipify.org 2>/dev/null || true)"
fi
if [[ -z "$PUBLIC_IP" ]]; then
  PUBLIC_IP="$(hostname -I | awk '{print $1}')"
fi
DNS_IP="$(getent ahostsv4 "$DOMAIN" | awk 'NR==1{print $1}' || true)"
say "آی‌پی سرور: $PUBLIC_IP — آی‌پی دامنه $DOMAIN: ${DNS_IP:-پیدا نشد}"
if [[ -z "$DNS_IP" ]]; then
  fail "دامنه $DOMAIN به هیچ آی‌پی اشاره نمی‌کند؛ رکورد A را در DNS ثبت کنید و چند دقیقه بعد دوباره اجرا کنید."
fi
if [[ "$DNS_IP" != "$PUBLIC_IP" ]]; then
  echo "هشدار: دامنه به $DNS_IP اشاره می‌کند اما آی‌پی سرور $PUBLIC_IP تشخیص داده شد."
  echo "اگر آی‌پی سرور چیز دیگری است، آن را این‌طور بدهید: PUBLIC_IP=$DNS_IP sudo -E bash $0 $DOMAIN $EMAIL"
  PUBLIC_IP="$DNS_IP"
fi

# ── Ports ────────────────────────────────────────────────────────────────────
# If ports 80/443 already belong to a Caddy container (another site on this server), the webinar
# runs behind it: Caddy keeps 80/443, gets the certificate and forwards the webinar domain.
PROXY_CONTAINER="${PROXY_CONTAINER:-}"
port_in_use() {
  if command -v ss >/dev/null; then ss -ltnH "sport = :$1" | grep -q .; else (exec 3<>"/dev/tcp/127.0.0.1/$1") 2>/dev/null; fi
}
if [[ -z "$PROXY_CONTAINER" ]]; then
  for port in 80 443; do
    owner="$(docker ps --format '{{.Names}} {{.Image}} {{.Ports}}' | grep -E "(0\.0\.0\.0|\[::\]):$port->" | grep -v '^kx-webinar-' | head -1 || true)"
    if [[ "$owner" == *caddy* ]]; then
      PROXY_CONTAINER="${owner%% *}"
      break
    fi
    if [[ -n "$owner" ]] || { port_in_use "$port" && ! docker ps --format '{{.Names}}' | grep -q '^kx-webinar-web'; }; then
      command -v ss >/dev/null && ss -ltnpH "sport = :$port" || true
      [[ -n "$owner" ]] && echo "کانتینر: $owner"
      fail "پورت $port روی این سرور در اختیار برنامه دیگری است (بالا نمایش داده شد). وبینار برای گواهی SSL به پورت‌های 80 و 443 یا یک Caddy موجود نیاز دارد."
    fi
  done
fi
if [[ -n "$PROXY_CONTAINER" ]]; then
  say "پورت‌های 80 و 443 در اختیار Caddy ($PROXY_CONTAINER) است؛ وبینار پشت همان Caddy راه‌اندازی می‌شود."
fi
if command -v ss >/dev/null && ss -lunH "sport = :10000" | grep -q . && ! docker ps --format '{{.Names}}' | grep -q "^kx-webinar-jvb"; then
  fail "پورت 10000/udp (صدا و تصویر وبینار) در اختیار برنامه دیگری است."
fi

# ── Settings (.env); secrets are kept on re-runs ─────────────────────────────
# Release matching docker-compose.yml (the last one published on Docker Hub).
JITSI_VERSION=stable-11031
get() { [[ -f .env ]] && grep -E "^$1=" .env | head -1 | cut -d= -f2- || true; }
rand() { openssl rand -hex "${1:-16}"; }
JWT_SECRET="$(get JWT_APP_SECRET)"; JWT_SECRET="${JWT_SECRET:-$(rand 32)}"
JICOFO_PW="$(get JICOFO_AUTH_PASSWORD)"; JICOFO_PW="${JICOFO_PW:-$(rand)}"
JVB_PW="$(get JVB_AUTH_PASSWORD)"; JVB_PW="${JVB_PW:-$(rand)}"

if [[ -n "$PROXY_CONTAINER" ]]; then
  # Behind the existing Caddy: HTTPS and the certificate are handled by Caddy.
  PORT_SETTINGS="HTTP_PORT=127.0.0.1:8800
HTTPS_PORT=127.0.0.1:8843
DISABLE_HTTPS=1
ENABLE_HTTP_REDIRECT=0
ENABLE_LETSENCRYPT=0"
else
  PORT_SETTINGS="HTTP_PORT=80
HTTPS_PORT=443
ENABLE_HTTP_REDIRECT=1
ENABLE_LETSENCRYPT=1
LETSENCRYPT_DOMAIN=$DOMAIN
LETSENCRYPT_EMAIL=$EMAIL"
fi

say "نوشتن تنظیمات وبینار در $DIR/.env"
umask 077
cat > .env <<ENV
# Generated by install.sh — re-run the script to change the domain.
COMPOSE_PROJECT_NAME=kx-webinar
JITSI_IMAGE_VERSION=$JITSI_VERSION
RESTART_POLICY=unless-stopped
ENABLE_IPV6=0
CONFIG=$DIR/config
TZ=Asia/Tehran

PUBLIC_URL=https://$DOMAIN
$PORT_SETTINGS
JVB_ADVERTISE_IPS=$PUBLIC_IP
JVB_PORT=10000
# Local-only admin ports, moved off 8080/8888 which other apps often use.
JVB_COLIBRI_PORT=18080
JICOFO_REST_PORT=18888

# Only people sent by the commissions platform (signed token) can enter a room.
ENABLE_AUTH=1
AUTH_TYPE=jwt
ENABLE_GUESTS=0
JWT_APP_ID=kx-commissions
JWT_APP_SECRET=$JWT_SECRET
JWT_ACCEPTED_ISSUERS=kx-commissions
JWT_ACCEPTED_AUDIENCES=jitsi
JWT_ALLOW_EMPTY=0
# Moderator rights come from the token (chair, vice-chair, secretary) through token_affiliation.
# Jicofo must not grant them itself (to the first or to every authenticated participant);
# Prosody still refuses anyone without a valid token.
XMPP_MUC_MODULES=token_affiliation
ENABLE_AUTO_OWNER=false
JICOFO_ENABLE_AUTH=0

DEFAULT_LANGUAGE=fa
ENABLE_WELCOME_PAGE=0
ENABLE_CLOSE_PAGE=0
ENABLE_PREJOIN_PAGE=1
ENABLE_BREAKOUT_ROOMS=0
ENABLE_RECORDING=0
# Local recording: the chair/secretary record in their own browser (Chrome/Edge); everyone is told when it starts.
# Other participants get no record button (see webinarJoinUrl in the api).
DISABLE_LOCAL_RECORDING=false
ENABLE_LOCAL_RECORDING_NOTIFY_ALL_PARTICIPANT=true

JICOFO_AUTH_PASSWORD=$JICOFO_PW
JVB_AUTH_PASSWORD=$JVB_PW
JIGASI_XMPP_PASSWORD=$(rand)
JIGASI_TRANSCRIBER_PASSWORD=$(rand)
JIBRI_RECORDER_PASSWORD=$(rand)
JIBRI_XMPP_PASSWORD=$(rand)
ENV
umask 022
mkdir -p config/{web,transcripts,prosody/config,prosody/prosody-plugins-custom,jicofo,jvb}

# ── Firewall ─────────────────────────────────────────────────────────────────
if command -v ufw >/dev/null && ufw status | grep -q "Status: active"; then
  say "باز کردن پورت‌های 80، 443 و 10000/udp در فایروال"
  ufw allow 80/tcp >/dev/null; ufw allow 443/tcp >/dev/null; ufw allow 10000/udp >/dev/null
fi

# ── Start Jitsi ──────────────────────────────────────────────────────────────
say "دریافت و اجرای سرویس‌های وبینار (اولین بار چند دقیقه طول می‌کشد)"
# If Docker Hub is not reachable, pass a registry mirror, e.g. REGISTRY_MIRROR=docker.arvancloud.ir
if [[ -n "${REGISTRY_MIRROR:-}" ]]; then
  for svc in web prosody jicofo jvb; do
    docker pull "$REGISTRY_MIRROR/jitsi/$svc:$JITSI_VERSION"
    docker tag "$REGISTRY_MIRROR/jitsi/$svc:$JITSI_VERSION" "jitsi/$svc:$JITSI_VERSION"
  done
else
  docker compose pull || fail "دریافت ایمیج‌ها از Docker Hub ممکن نشد؛ با یک میرور دوباره اجرا کنید:  REGISTRY_MIRROR=docker.arvancloud.ir sudo -E bash $0 $DOMAIN $EMAIL"
fi
docker compose up -d

# ── Route the domain through the existing Caddy ──────────────────────────────
if [[ -n "$PROXY_CONTAINER" ]]; then
  say "افزودن $DOMAIN به Caddy ($PROXY_CONTAINER)"
  NET="kx-webinar_meet.jitsi"
  if ! docker inspect -f '{{json .NetworkSettings.Networks}}' "$PROXY_CONTAINER" | grep -q "\"$NET\""; then
    docker network connect "$NET" "$PROXY_CONTAINER"
  fi
  CADDYFILE="$(docker inspect -f '{{range .Mounts}}{{if eq .Destination "/etc/caddy/Caddyfile"}}{{.Source}}{{end}}{{end}}' "$PROXY_CONTAINER")"
  if [[ -z "$CADDYFILE" ]]; then
    CADDYDIR="$(docker inspect -f '{{range .Mounts}}{{if eq .Destination "/etc/caddy"}}{{.Source}}{{end}}{{end}}' "$PROXY_CONTAINER")"
    [[ -n "$CADDYDIR" ]] && CADDYFILE="$CADDYDIR/Caddyfile"
  fi
  BLOCK="$DOMAIN {
	# Built-in webinar of the commissions platform (deploy/webinar/install.sh)
	reverse_proxy kx-webinar-web-1:80
}"
  if [[ -z "$CADDYFILE" || ! -f "$CADDYFILE" ]]; then
    echo "فایل Caddyfile این کانتینر پیدا نشد. این بخش را خودتان به Caddyfile اضافه کنید و Caddy را reload کنید:"
    echo "$BLOCK"
  elif grep -qE "^[[:space:]]*$DOMAIN[[:space:]]*\{" "$CADDYFILE"; then
    echo "دامنه $DOMAIN از قبل در $CADDYFILE تعریف شده است؛ تغییری داده نشد."
  else
    cp "$CADDYFILE" "$CADDYFILE.bak.$(date +%Y%m%d%H%M%S)"
    printf '\n%s\n' "$BLOCK" >> "$CADDYFILE"
    echo "به $CADDYFILE اضافه شد (نسخه پشتیبان کنار همان فایل است)."
  fi
  # A single-file bind mount keeps showing the old file if an editor replaced it on the host;
  # restarting the container re-binds the current file. Reload validates before applying.
  if ! docker exec "$PROXY_CONTAINER" grep -q "$DOMAIN" /etc/caddy/Caddyfile; then
    echo "Caddy نسخه قدیمی Caddyfile را می‌بیند؛ کانتینر $PROXY_CONTAINER دوباره اجرا می‌شود (چند ثانیه)."
    docker restart "$PROXY_CONTAINER" >/dev/null
    sleep 3
  elif ! docker exec "$PROXY_CONTAINER" caddy reload --config /etc/caddy/Caddyfile --adapter caddyfile; then
    echo "reload ناموفق بود؛ Caddy را دوباره اجرا می‌کنم."
    docker restart "$PROXY_CONTAINER" >/dev/null
  fi
  docker exec "$PROXY_CONTAINER" grep -q "$DOMAIN" /etc/caddy/Caddyfile \
    || fail "Caddy هنوز دامنه $DOMAIN را در تنظیماتش نمی‌بیند؛ Caddyfile داخل کانتینر $PROXY_CONTAINER را بررسی کنید."
  echo "نکته: اگر کانتینر $PROXY_CONTAINER از نو ساخته شود (docker compose up در پروژه دیگر)، این اسکریپت را دوباره اجرا کنید تا اتصال شبکه برقرار بماند."
fi

# ── Connect the platform ─────────────────────────────────────────────────────
if [[ -f "$ROOT/.env" ]]; then
  say "اتصال سامانه کمیسیون‌ها به وبینار"
  sed -i '/^WEBINAR_URL=/d;/^WEBINAR_APP_ID=/d;/^WEBINAR_APP_SECRET=/d' "$ROOT/.env"
  {
    echo "WEBINAR_URL=https://$DOMAIN"
    echo "WEBINAR_APP_ID=kx-commissions"
    echo "WEBINAR_APP_SECRET=$JWT_SECRET"
  } >> "$ROOT/.env"
  (cd "$ROOT" && docker compose up -d --force-recreate api)
else
  echo "فایل $ROOT/.env پیدا نشد؛ این سه خط را به تنظیمات سامانه اضافه کنید و API را دوباره اجرا کنید:"
  echo "WEBINAR_URL=https://$DOMAIN"
  echo "WEBINAR_APP_ID=kx-commissions"
  echo "WEBINAR_APP_SECRET=$JWT_SECRET"
fi

say "صبر برای صدور گواهی SSL و آماده شدن https://$DOMAIN"
for _ in $(seq 1 36); do
  # Ask this server directly: many servers cannot reach their own public IP (NAT hairpin).
  # The certificate is still checked against the domain name.
  if curl -fs --max-time 5 --resolve "$DOMAIN:443:127.0.0.1" -o /dev/null "https://$DOMAIN/config.js"; then
    printf '\n\033[1;32m✓ وبینار آماده است: https://%s\033[0m\n' "$DOMAIN"
    echo "از این پس در جلسات «آنلاین» و «ترکیبی» دکمه «ورود به وبینار» در سامانه و اپ نمایش داده می‌شود."
    exit 0
  fi
  sleep 5
done
echo "وبینار هنوز روی https پاسخ نمی‌دهد. ابتدا https://$DOMAIN را در مرورگر خودتان باز کنید؛ اگر باز نشد:"
if [[ -n "$PROXY_CONTAINER" ]]; then
  echo "  docker logs $PROXY_CONTAINER --since 30m 2>&1 | grep -i $DOMAIN | tail -20"
fi
echo "  cd $DIR && docker compose ps && docker compose logs web | tail -50"
exit 1
