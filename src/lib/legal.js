export const LEGAL_ORDER = ['terms', 'privacy', 'telehealth', 'support'];

export function legalDoc(id, settings) {
  if (!Object.hasOwn(DOCS, id)) return null;
  return { id, updated: LEGAL_UPDATED, company: COMPANY, ...DOCS[id](settings) };
}

export function legalIndex(settings) {
  return LEGAL_ORDER.map((id) => ({ id, title: DOCS[id](settings).title }));
}
